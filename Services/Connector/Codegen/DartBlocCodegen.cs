using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using Syncro.Desktop.Services.Connector.Models;

namespace Syncro.Desktop.Services.Connector.Codegen
{
    /// <summary>
    /// Phase 3 — Dart/BLoC codegen from a <see cref="BackendContract"/>.
    ///
    /// Groups routes by feature (first meaningful path segment) and writes 4 Dart files per
    /// feature into <c>{frontendRoot}/lib/features/{feature}/</c>:
    ///   • {feature}_dto.dart      — immutable data class + fromJson / toJson
    ///   • {feature}_repository.dart — abstract interface + http implementation
    ///   • {feature}_state.dart    — Equatable state hierarchy
    ///   • {feature}_bloc.dart     — events + BLoC class wired to the repository
    ///
    /// Files are only written when the frontend directory exists, so the service is safe
    /// to call from subscribers even when no Flutter project is connected.
    /// </summary>
    public sealed class DartBlocCodegen
    {
        private static readonly string[] SkipSegments = { "api", "v1", "v2", "v3", "mobile" };

        public async Task<CodegenResult> GenerateAsync(BackendContract contract, string frontendRoot)
        {
            var result = new CodegenResult { FrontendRoot = frontendRoot };

            if (!Directory.Exists(frontendRoot))
            {
                result.Notes.Add($"Frontend root not found: {frontendRoot}");
                return result;
            }

            var groups = GroupByFeature(contract.Routes);
            foreach (var (feature, routes) in groups)
            {
                var dir = Path.Combine(frontendRoot, "lib", "features", feature);
                Directory.CreateDirectory(dir);

                var dtoFile = Path.Combine(dir, $"{feature}_dto.dart");
                var repoFile = Path.Combine(dir, $"{feature}_repository.dart");
                var stateFile = Path.Combine(dir, $"{feature}_state.dart");
                var blocFile = Path.Combine(dir, $"{feature}_bloc.dart");

                await File.WriteAllTextAsync(dtoFile, BuildDto(feature, routes), Encoding.UTF8);
                await File.WriteAllTextAsync(repoFile, BuildRepository(feature, routes), Encoding.UTF8);
                await File.WriteAllTextAsync(stateFile, BuildState(feature), Encoding.UTF8);
                await File.WriteAllTextAsync(blocFile, BuildBloc(feature, routes), Encoding.UTF8);

                result.FeaturesGenerated.Add(feature);
                result.FilesWritten += 4;
            }

            return result;
        }

        // ── Feature grouping ─────────────────────────────────────────────────────────

        private static Dictionary<string, List<BackendRoute>> GroupByFeature(List<BackendRoute> routes)
        {
            var groups = new Dictionary<string, List<BackendRoute>>(StringComparer.OrdinalIgnoreCase);
            foreach (var r in routes)
            {
                var feature = ExtractFeature(r.PathTemplate);
                if (!groups.TryGetValue(feature, out var list))
                    groups[feature] = list = new List<BackendRoute>();
                list.Add(r);
            }
            return groups;
        }

        private static string ExtractFeature(string pathTemplate)
        {
            var segments = pathTemplate.Split('/', StringSplitOptions.RemoveEmptyEntries);
            foreach (var seg in segments)
            {
                if (seg.StartsWith('{')) continue;
                if (SkipSegments.Contains(seg, StringComparer.OrdinalIgnoreCase)) continue;
                return ToSnakeCase(seg);
            }
            return "unknown";
        }

        // ── DTO generation ───────────────────────────────────────────────────────────

        private static string BuildDto(string feature, List<BackendRoute> routes)
        {
            var pascal = ToPascalCase(feature);
            // Collect all unique response fields across routes for the primary DTO.
            var fields = routes
                .SelectMany(r => r.ResponseSchema)
                .GroupBy(f => f.Name, StringComparer.OrdinalIgnoreCase)
                .Select(g => g.First())
                .ToList();

            var sb = new StringBuilder();
            sb.AppendLine("// AUTO-GENERATED by Syncro Contract Engine — do not edit manually.");
            sb.AppendLine("// Re-run from the Syncro IDE when the backend contract drifts.");
            sb.AppendLine();
            sb.AppendLine("import 'package:equatable/equatable.dart';");
            sb.AppendLine();
            sb.AppendLine($"class {pascal}Dto extends Equatable {{");

            foreach (var f in fields)
                sb.AppendLine($"  final {DartType(f.Type)}{(f.Required ? "" : "?")} {ToCamelCase(f.Name)};");

            sb.AppendLine();

            // Constructor
            sb.AppendLine($"  const {pascal}Dto({{");
            foreach (var f in fields)
                sb.AppendLine($"    {(f.Required ? "required " : "")}this.{ToCamelCase(f.Name)},");
            sb.AppendLine("  });");
            sb.AppendLine();

            // fromJson
            sb.AppendLine($"  factory {pascal}Dto.fromJson(Map<String, dynamic> json) => {pascal}Dto(");
            foreach (var f in fields)
            {
                var cast = DartFromJsonCast(f.Type, $"json['{f.Name}']");
                sb.AppendLine($"    {ToCamelCase(f.Name)}: {cast},");
            }
            sb.AppendLine("  );");
            sb.AppendLine();

            // toJson
            sb.AppendLine("  Map<String, dynamic> toJson() => {");
            foreach (var f in fields)
                sb.AppendLine($"    '{f.Name}': {ToCamelCase(f.Name)},");
            sb.AppendLine("  };");
            sb.AppendLine();

            sb.AppendLine("  @override");
            var propList = fields.Count == 0 ? "[]" : $"[{string.Join(", ", fields.Select(f => ToCamelCase(f.Name)))}]";
            sb.AppendLine($"  List<Object?> get props => {propList};");
            sb.AppendLine("}");

            return sb.ToString();
        }

        // ── Repository generation ────────────────────────────────────────────────────

        private static string BuildRepository(string feature, List<BackendRoute> routes)
        {
            var pascal = ToPascalCase(feature);
            var sb = new StringBuilder();
            sb.AppendLine("// AUTO-GENERATED by Syncro Contract Engine.");
            sb.AppendLine();
            sb.AppendLine("import 'dart:convert';");
            sb.AppendLine("import 'package:http/http.dart' as http;");
            sb.AppendLine($"import '{feature}_dto.dart';");
            sb.AppendLine();

            // Abstract interface
            sb.AppendLine($"abstract class {pascal}Repository {{");
            foreach (var r in routes)
            {
                var method = MethodName(r.Method, r.PathTemplate);
                sb.AppendLine($"  Future<List<{pascal}Dto>> {method}();");
            }
            sb.AppendLine("}");
            sb.AppendLine();

            // HTTP implementation
            sb.AppendLine($"class {pascal}RepositoryImpl implements {pascal}Repository {{");
            sb.AppendLine("  final String baseUrl;");
            sb.AppendLine($"  {pascal}RepositoryImpl({{required this.baseUrl}});");
            sb.AppendLine();

            foreach (var r in routes)
            {
                var method = MethodName(r.Method, r.PathTemplate);
                var httpMethod = r.Method.ToString().ToLowerInvariant();
                sb.AppendLine("  @override");
                sb.AppendLine($"  Future<List<{pascal}Dto>> {method}() async {{");
                sb.AppendLine($"    final res = await http.{httpMethod}(Uri.parse('$baseUrl{r.PathTemplate}'));");
                sb.AppendLine("    if (res.statusCode != 200) throw Exception('HTTP ${{res.statusCode}}');");
                sb.AppendLine("    final list = jsonDecode(res.body) as List;");
                sb.AppendLine($"    return list.map((e) => {pascal}Dto.fromJson(e as Map<String, dynamic>)).toList();");
                sb.AppendLine("  }");
                sb.AppendLine();
            }

            sb.AppendLine("}");
            return sb.ToString();
        }

        // ── State generation ─────────────────────────────────────────────────────────

        private static string BuildState(string feature)
        {
            var pascal = ToPascalCase(feature);
            return $@"// AUTO-GENERATED by Syncro Contract Engine.

import 'package:equatable/equatable.dart';
import '{feature}_dto.dart';

abstract class {pascal}State extends Equatable {{
  const {pascal}State();
}}

class {pascal}Initial extends {pascal}State {{
  const {pascal}Initial();
  @override List<Object?> get props => [];
}}

class {pascal}Loading extends {pascal}State {{
  const {pascal}Loading();
  @override List<Object?> get props => [];
}}

class {pascal}Loaded extends {pascal}State {{
  final List<{pascal}Dto> items;
  const {pascal}Loaded(this.items);
  @override List<Object?> get props => [items];
}}

class {pascal}Error extends {pascal}State {{
  final String message;
  const {pascal}Error(this.message);
  @override List<Object?> get props => [message];
}}
";
        }

        // ── BLoC generation ──────────────────────────────────────────────────────────

        private static string BuildBloc(string feature, List<BackendRoute> routes)
        {
            var pascal = ToPascalCase(feature);
            var sb = new StringBuilder();
            sb.AppendLine("// AUTO-GENERATED by Syncro Contract Engine.");
            sb.AppendLine();
            sb.AppendLine("import 'package:flutter_bloc/flutter_bloc.dart';");
            sb.AppendLine($"import '{feature}_repository.dart';");
            sb.AppendLine($"import '{feature}_state.dart';");
            sb.AppendLine();

            // Events
            sb.AppendLine($"abstract class {pascal}Event {{}}");
            sb.AppendLine();
            foreach (var r in routes)
            {
                var evtName = $"{EventName(r.Method, r.PathTemplate)}{pascal}";
                sb.AppendLine($"class {evtName} extends {pascal}Event {{}}");
            }
            sb.AppendLine();

            // BLoC
            sb.AppendLine($"class {pascal}Bloc extends Bloc<{pascal}Event, {pascal}State> {{");
            sb.AppendLine($"  final {pascal}Repository _repository;");
            sb.AppendLine();
            sb.AppendLine($"  {pascal}Bloc({{required {pascal}Repository repository}})");
            sb.AppendLine($"      : _repository = repository,");
            sb.AppendLine($"        super(const {pascal}Initial()) {{");

            foreach (var r in routes)
            {
                var evtName = $"{EventName(r.Method, r.PathTemplate)}{pascal}";
                var repoMethod = MethodName(r.Method, r.PathTemplate);
                sb.AppendLine($"    on<{evtName}>((event, emit) async {{");
                sb.AppendLine($"      emit(const {pascal}Loading());");
                sb.AppendLine("      try {");
                sb.AppendLine($"        final items = await _repository.{repoMethod}();");
                sb.AppendLine($"        emit({pascal}Loaded(items));");
                sb.AppendLine($"      }} catch (e) {{");
                sb.AppendLine($"        emit({pascal}Error(e.toString()));");
                sb.AppendLine("      }");
                sb.AppendLine("    });");
            }

            sb.AppendLine("  }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        // ── Naming helpers ───────────────────────────────────────────────────────────

        private static string MethodName(HttpVerb verb, string path)
        {
            var feature = ExtractFeature(path);
            return verb switch
            {
                HttpVerb.Get => $"fetch{ToPascalCase(feature)}",
                HttpVerb.Post => $"create{ToPascalCase(feature)}",
                HttpVerb.Put or HttpVerb.Patch => $"update{ToPascalCase(feature)}",
                HttpVerb.Delete => $"delete{ToPascalCase(feature)}",
                _ => $"call{ToPascalCase(feature)}"
            };
        }

        private static string EventName(HttpVerb verb, string path)
        {
            return verb switch
            {
                HttpVerb.Get => "Fetch",
                HttpVerb.Post => "Create",
                HttpVerb.Put or HttpVerb.Patch => "Update",
                HttpVerb.Delete => "Delete",
                _ => "Call"
            };
        }

        private static string DartType(string jsonType) => jsonType?.ToLowerInvariant() switch
        {
            "integer" or "int" => "int",
            "number" or "double" or "float" => "double",
            "boolean" or "bool" => "bool",
            "array" => "List<dynamic>",
            "object" => "Map<String, dynamic>",
            _ => "String"
        };

        private static string DartFromJsonCast(string jsonType, string expr) => jsonType?.ToLowerInvariant() switch
        {
            "integer" or "int" => $"({expr} as num?)?.toInt()",
            "number" or "double" or "float" => $"({expr} as num?)?.toDouble()",
            "boolean" or "bool" => $"{expr} as bool?",
            _ => $"{expr} as String?"
        };

        private static string ToPascalCase(string s)
        {
            if (string.IsNullOrEmpty(s)) return s;
            s = s.Replace('-', '_');
            var parts = s.Split('_', StringSplitOptions.RemoveEmptyEntries);
            return string.Concat(parts.Select(p => char.ToUpperInvariant(p[0]) + p[1..]));
        }

        private static string ToCamelCase(string s)
        {
            var p = ToPascalCase(s);
            if (string.IsNullOrEmpty(p)) return p;
            return char.ToLowerInvariant(p[0]) + p[1..];
        }

        private static string ToSnakeCase(string s)
        {
            if (string.IsNullOrEmpty(s)) return s;
            var sb = new StringBuilder();
            for (int i = 0; i < s.Length; i++)
            {
                if (char.IsUpper(s[i]) && i > 0) sb.Append('_');
                sb.Append(char.ToLowerInvariant(s[i]));
            }
            return sb.ToString().Replace('-', '_');
        }
    }

    public sealed class CodegenResult
    {
        public string FrontendRoot { get; set; } = "";
        public List<string> FeaturesGenerated { get; } = new();
        public int FilesWritten { get; set; }
        public List<string> Notes { get; } = new();
    }
}
